//! Per-model prices, so a charge can use the real price of the model you called
//! instead of a rough tier average.
//!
//! # Where the built-in prices come from
//!
//! [`PriceTable::builtin`] layers two sources:
//!
//! 1. The [`llm-prices`](https://docs.rs/llm-prices) crate: dated,
//!    source-cited prices for Anthropic, OpenAI, Google Gemini and DeepSeek,
//!    with long-context tiers. It wins for every model it lists, and
//!    [`PriceTable::cost_usage`] uses its long-context prices when a prompt
//!    crosses a model's threshold. [`LLM_PRICES_DATE`] says when it was
//!    generated. Its id lookup also resolves Bedrock and Vertex ids
//!    (`us.anthropic.claude-sonnet-4-6-v1:0`, `claude-opus-4-1@20250805`).
//! 2. A snapshot of LiteLLM's `model_prices_and_context_window.json` (MIT
//!    license), generated by `scripts/update_prices.py`, for the models
//!    llm-prices does not list (Mistral, xAI and older ids) and for context
//!    sizes. [`SNAPSHOT_DATE`] says when it was generated. You can load a newer
//!    copy of that file at runtime with [`PriceTable::from_litellm_json`].
//!
//! # Overriding prices
//!
//! Negotiated rates, fine-tunes and self-hosted models need your own numbers.
//! [`PriceTable::cost_usage`] looks in this order: the
//! [hook](PriceTable::with_hook), prices you [`insert`](PriceTable::insert)ed,
//! llm-prices, then the table's own rows. Give an
//! [`AgentBudget`](crate::AgentBudget) your table with
//! [`AgentBudgetBuilder::price_table`](crate::AgentBudgetBuilder::price_table).
//!
//! ```
//! use llm_budget::pricing::{ModelPrice, PriceTable};
//! use llm_budget::Usage;
//!
//! let mut table = PriceTable::builtin().clone();
//! // A negotiated gpt-4o rate: half price.
//! table.insert(ModelPrice::new("gpt-4o", "openai", 1.25, 5.0));
//! let usd = table.cost_usage("gpt-4o", &Usage::new(1_000_000, 0))?;
//! assert!((usd - 1.25).abs() < 1e-9);
//!
//! // Or decide per call, for example from a pricing service of your own.
//! let table = table.with_hook(|model, usage| {
//!     (model == "my-finetune").then(|| usage.output_tokens as f64 * 4e-6)
//! });
//! assert!((table.cost_usage("my-finetune", &Usage::new(0, 1_000))? - 0.004).abs() < 1e-12);
//! # Ok::<(), llm_budget::BudgetError>(())
//! ```
//!
//! # Looking up one model
//!
//! ```
//! use llm_budget::pricing::PriceTable;
//!
//! let table = PriceTable::builtin();
//! let price = table.get("gpt-4o").expect("gpt-4o is in the table");
//! // 1,000 input tokens and 500 output tokens:
//! let usd = price.cost(1_000, 500);
//! assert!((usd - (1_000.0 * 2.5 + 500.0 * 10.0) / 1_000_000.0).abs() < 1e-12);
//! ```
//!
//! # When there is no price
//!
//! [`PriceTable::lookup`] says *why* a model could not be priced, as a
//! [`PriceStatus`]: the catalog knows the model but has no usable price
//! ([`Unpriced`](PriceStatus::Unpriced)), no source knows the model
//! ([`Missing`](PriceStatus::Missing)), or there is no price data to look in
//! ([`NoCatalog`](PriceStatus::NoCatalog)). An [`UnpricedPolicy`] picks a
//! [`PriceAction`] for each, so a self-hosted model can be let through while
//! a typo in a model id is refused:
//!
//! ```
//! use llm_budget::pricing::{PriceAction, PriceStatus, PriceTable, UnpricedPolicy};
//! use llm_budget::{AgentBudget, BudgetError, Usage};
//!
//! # fn main() -> Result<(), BudgetError> {
//! let table = PriceTable::builtin().clone().with_unpriced("in-house-70b");
//! let policy = UnpricedPolicy::new(
//!     PriceAction::Reserve(0.05), // listed without a price: hold a flat $0.05
//!     PriceAction::Deny,          // an id nobody knows: refuse before the call
//!     PriceAction::Deny,          // no price data at all: refuse
//! );
//! let agent = AgentBudget::builder("a", 1.0).price_table(table).unpriced_policy(policy).build()?;
//!
//! let hold = agent.reserve_for("in-house-70b", &Usage::new(1_000, 500))?;
//! assert_eq!(hold.price_status(), PriceStatus::Unpriced);
//! assert!((hold.estimate_usd() - 0.05).abs() < 1e-12);
//! hold.release();
//!
//! let err = agent.reserve_for("gtp-4o", &Usage::new(1_000, 500)).unwrap_err();
//! assert!(matches!(err, BudgetError::Unpriced { status: PriceStatus::Missing, .. }));
//! # Ok(())
//! # }
//! ```

